EDITS = []


def apply(ed, texts):
    """Применить решения; вернуть список неприменённых."""
    bad = []
    for n, t in WHOLE.get(ed, {}).items():
        texts[n] = t
    for e, n, old, new in EDITS:
        if e != ed:
            continue
        t = texts.get(n, "")
        if isinstance(old, R):
            t2 = re.sub(old, new, t, flags=re.S)
        else:
            t2 = t.replace(old, new)
        if t2 == t:
            bad.append((e, n, old))
        texts[n] = t2
    return bad
